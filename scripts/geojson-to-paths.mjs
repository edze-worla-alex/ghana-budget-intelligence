// Regenerate data/ghana-map.ts from an open GeoJSON of Ghana's 16 regions (e.g. geoBoundaries GHA ADM1, CC BY 4.0).
// Usage: node scripts/geojson-to-paths.mjs path/to/regions.geojson [nameProperty]
// nameProperty defaults to the first of: shapeName, name, NAME_1, region, REGION. Run, then `npm run typecheck`.
import { readFileSync, writeFileSync } from "node:fs";

const [file, prop] = process.argv.slice(2);
if (!file) { console.error("usage: node scripts/geojson-to-paths.mjs regions.geojson [nameProperty]"); process.exit(1); }
const gj = JSON.parse(readFileSync(file, "utf8"));
const feats = gj.type === "FeatureCollection" ? gj.features : [gj];

const IDS = { "upper west": "upper-west", "upper east": "upper-east", "north east": "north-east", northeast: "north-east", savannah: "savannah", northern: "northern",
  bono: "bono", "bono east": "bono-east", oti: "oti", "western north": "western-north", ahafo: "ahafo", ashanti: "ashanti", eastern: "eastern", volta: "volta",
  western: "western", central: "central", "greater accra": "greater-accra" };
const NAMES = Object.fromEntries(Object.entries(IDS).map(([k, v]) => [v, k.replace(/\b\w/g, (c) => c.toUpperCase()).replace("Northeast", "North East")]));
const nameOf = (f) => { const p = f.properties ?? {}; const k = prop ?? ["shapeName", "name", "NAME_1", "region", "REGION"].find((x) => p[x]); return String(p[k] ?? "").toLowerCase().replace(/ region$/, "").trim(); };

const polys = (g) => (g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : []);
const all = feats.flatMap((f) => polys(f.geometry).flat(2).length ? [f] : []);
const pts = all.flatMap((f) => polys(f.geometry).flatMap((p) => p.flat()));
const lat0 = pts.reduce((s, p) => s + p[1], 0) / pts.length, k = Math.cos((lat0 * Math.PI) / 180);
const minX = Math.min(...pts.map((p) => p[0] * k)), maxY = Math.max(...pts.map((p) => p[1]));
const SCALE = 120; // output units per degree
const X = (lon) => (lon * k - minX) * SCALE + 6, Y = (lat) => (maxY - lat) * SCALE + 6;
const W = Math.ceil((Math.max(...pts.map((p) => p[0] * k)) - minX) * SCALE + 12), H = Math.ceil((maxY - Math.min(...pts.map((p) => p[1]))) * SCALE + 12);

const out = {}; const missing = [];
for (const f of all) {
  const id = IDS[nameOf(f)]; if (!id) { missing.push(nameOf(f)); continue; }
  const d = polys(f.geometry).map((poly) => poly.map((ring) => "M" + ring.map(([x, y]) => `${X(x).toFixed(1)},${Y(y).toFixed(1)}`).join("L") + "Z").join("")).join("");
  const ring = polys(f.geometry).sort((a, b) => b[0].length - a[0].length)[0][0];
  const cx = ring.reduce((s, p) => s + X(p[0]), 0) / ring.length, cy = ring.reduce((s, p) => s + Y(p[1]), 0) / ring.length;
  (out[id] ??= { paths: [], label: [+cx.toFixed(1), +cy.toFixed(1)] }).paths.push(d);
}
const body = Object.entries(out).map(([id, v]) => `  "${id}": { name: "${NAMES[id]}", label: [${v.label}], paths: ${JSON.stringify(v.paths)} },`).join("\n");
writeFileSync("data/ghana-map.ts", `// Generated by scripts/geojson-to-paths.mjs from ${file}\nimport type { RegionId } from "./types";\n\nexport const MAP_VIEWBOX = "0 0 ${W} ${H}";\nexport const REGION_SHAPES: Record<RegionId, { name: string; paths: string[]; label: [number, number] }> = {\n${body}\n};\n`);
console.log(`${Object.keys(out).length}/16 regions written.` + (missing.length ? ` Unmatched names: ${missing.join(", ")}` : ""));
if (Object.keys(out).length !== 16) console.warn("Warning: expected 16 regions; the map component needs all 16 keys to typecheck.");
